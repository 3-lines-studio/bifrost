var moduleCleaner = regexp.MustCompile(`[^a-zA-Z0-9._/-]+`)

func runInit(args []string) error {
	flags := flag.NewFlagSet("init", flag.ContinueOnError)
	noInstall := flags.Bool("no-install", false, "skip running go get, go mod tidy, and bun install after scaffolding")
	classic := flags.Bool("classic", false, "scaffold the classic router instead of the App Router")
	native := flags.Bool("native", false, "scaffold pages of native Go (MyGo) instead of React, with no Bun and no Vite")
	if err := flags.Parse(args); err != nil {
		return err
	}
	rest := flags.Args()
	if len(rest) != 1 {
		return fmt.Errorf("usage: bifrost init [--no-install] [--classic] <directory>")
	}
	directory, err := filepath.Abs(rest[0])
	if err != nil {
		return err
	}
	module := moduleCleaner.ReplaceAllString(filepath.Base(directory), "-")
	files := map[string]string{
		"go.mod":                     "module " + module + "\n\ngo 1.27.0\n",
		"package.json":               "{\n  \"private\": true,\n  \"type\": \"module\",\n  \"dependencies\": {\n    \"react\": \"19.2.4\",\n    \"react-dom\": \"19.2.4\"\n  },\n  \"devDependencies\": {\n    \"@tailwindcss/vite\": \"4.3.3\",\n    \"@types/react\": \"19.2.14\",\n    \"@types/react-dom\": \"19.2.3\",\n    \"@vitejs/plugin-react\": \"6.0.5\",\n    \"tailwindcss\": \"4.3.3\",\n    \"vite\": \"8.2.1\"\n  }\n}\n",
		"main.go":                    "package main\n\nimport (\n\t\"context\"\n\t\"log\"\n\t\"os\"\n\t\"os/signal\"\n\t\"syscall\"\n\n\t\"github.com/3-lines-studio/bifrost\"\n)\n\nfunc main() {\n\tapp, err := bifrost.New(bifrost.Config{\n\t\tAssets: bifrostAssets,\n\t\tRoutes: []bifrost.Route{bifrost.Server(\"/{$}\", \"pages/home.tsx\", nil)},\n\t})\n\tif err != nil { log.Fatal(err) }\n\tif bifrost.Building() { return }\n\tdefer app.Close(context.Background())\n\tctx, stop := signal.NotifyContext(context.Background(), os.Interrupt, syscall.SIGTERM)\n\tdefer stop()\n\tif err := bifrost.Serve(ctx, app.Handler()); err != nil { log.Print(err) }\n}\n",
		"pages/home.tsx":             "import React from 'react';\nimport './style.css';\n\nexport function Head() { return <title>Bifrost</title>; }\nexport function Page() { return <main className=\"p-6\"><h1>Bifrost</h1></main>; }\n",
		"pages/style.css":            "@import \"tailwindcss\";\n",
		"vite.config.ts":             "import { defineConfig } from 'vite';\nimport react from '@vitejs/plugin-react';\nimport tailwindcss from '@tailwindcss/vite';\n\nexport default defineConfig({ plugins: [react(), tailwindcss()] });\n",
		"bifrost.d.ts":               "declare module 'virtual:bifrost/routes' {\n  export interface BifrostRoute {\n    pattern: string;\n    view: string;\n    kind: 'server' | 'static' | 'client';\n  }\n\n  export const routes: BifrostRoute[];\n\n  export function href(pattern: string, params?: Record<string, string | string[]>): string;\n}\n\ndeclare module 'virtual:bifrost/navigation' {\n  export function navigate(href: string): Promise<void>;\n  export function replace(href: string): Promise<void>;\n  export function refresh(): Promise<void>;\n  export function Link(props: { href: string; children?: unknown } & Record<string, unknown>): any;\n  export function usePathname(): string;\n  export function useParams(): Record<string, string | string[]>;\n  export function useSearchParams(): URLSearchParams;\n  export function useRouter(): {\n    push(href: string): Promise<void>;\n    replace(href: string): Promise<void>;\n    refresh(): Promise<void>;\n    back(): void;\n    forward(): void;\n  };\n}\n",
		"zz_bifrost_gen.go":          "// Code generated by bifrost. DO NOT EDIT.\n\npackage main\n\nimport (\n\t\"embed\"\n\t\"io/fs\"\n)\n\n//go:embed all:.bifrost\nvar bifrostEmbedded embed.FS\n\nvar bifrostAssets fs.FS = func() fs.FS { assets, err := fs.Sub(bifrostEmbedded, \".bifrost\"); if err != nil { panic(err) }; return assets }()\n",
		".bifrost/embed.placeholder": "generated by bifrost\n",
		".gitignore":                 ".bifrost/*\n!.bifrost/embed.placeholder\nnode_modules/\n",
	}
	switch {
	case *native && *classic:
		return fmt.Errorf("init takes --native or --classic, not both")
	case *native:
		files = nativeScaffold(module, filepath.Base(directory))
	case !*classic:
		files = appRouterScaffold(module)
	}
	for name := range files {
		path := filepath.Join(directory, filepath.FromSlash(name))
		if _, err := os.Stat(path); err == nil {
			return fmt.Errorf("refusing to overwrite %s", path)
		}
	}
	for name, content := range files {
		path := filepath.Join(directory, filepath.FromSlash(name))
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			return err
		}
		data := []byte(content)
		if filepath.Ext(path) == ".go" {
			formatted, err := format.Source(data)
			if err != nil {
				return fmt.Errorf("format %s: %w", path, err)
			}
			data = formatted
		}
		if err := os.WriteFile(path, data, 0o644); err != nil {
			return err
		}
	}
	fmt.Printf("Created %s\n", directory)
	if *noInstall {
		if *native {
			fmt.Printf("Run: cd %s && go get -tool github.com/3-lines-studio/bifrost/cmd/bifrost@latest && go get github.com/3-lines-studio/bifrost/mygo@latest github.com/egoist/mygo@latest && go mod tidy\n", directory)
			return nil
		}
		fmt.Printf("Run: cd %s && go get -tool github.com/3-lines-studio/bifrost/cmd/bifrost@latest && go mod tidy && bun install\n", directory)
		return nil
	}
	runScaffoldStep(directory, "go", "get", "-tool", "github.com/3-lines-studio/bifrost/cmd/bifrost@latest")
	if !*native {
		runScaffoldStep(directory, "go", "mod", "tidy")
		runScaffoldStep(directory, "bun", "install")
		return nil
	}
	runScaffoldStep(directory, "go", "get", "github.com/3-lines-studio/bifrost/mygo@latest", "github.com/egoist/mygo@latest")
	runScaffoldStep(directory, "go", "mod", "tidy")
	return nil
}

func runScaffoldStep(directory string, args ...string) {
	command := exec.Command(args[0], args[1:]...)
	command.Dir = directory
	command.Stdout = os.Stdout
	command.Stderr = os.Stderr
	fmt.Printf("Running %s...\n", strings.Join(args, " "))
	if err := command.Run(); err != nil {
		fmt.Fprintf(os.Stderr, "bifrost: %s failed; run it manually before bifrost dev\n", strings.Join(args, " "))
	}
}

