func nativeScaffoldLayout(name string) string {
	return `package app

import "github.com/egoist/mygo/ui"

// Layout wraps the pages of this directory and the ones below it, on the
// server and in the app.
func Layout(page func(*ui.Context)) func(*ui.Context) {
	return func(c *ui.Context) {
		ui.Column(c).Padding(24).Gap(16).Children(func() {
			ui.Text(c, ` + strconv.Quote(name) + `).FontSize(18).Bold().Role(ui.RoleHeading).Level(2)
			page(c)
		})
	}
}
`
}

func nativeScaffoldError() string {
	return `package app

import (
	"github.com/3-lines-studio/bifrost/mygo/seo"
	"github.com/egoist/mygo/ui"
)

// Error answers a page whose Load failed, with the status the error wraps or a
// 500. It is never cached and never indexed.
func Error(err error) func(*ui.Context) {
	return func(c *ui.Context) {
		ui.Column(c).Padding(24).Gap(12).Children(func() {
			ui.Text(c, "Something went wrong").FontSize(28).Bold().Role(ui.RoleHeading).Level(1)
			ui.Text(c, "Try again in a moment.")
		})
	}
}

// ErrorMetadata is the title of the error page.
func ErrorMetadata() seo.Head {
	return seo.Head{Title: "Something went wrong"}
}
`
}

