func nativeScaffold(module, name string) map[string]string {
	display := strings.TrimSpace(name)
	if display == "" {
		display = "App"
	}
	identifier := "com.example." + strings.Map(func(r rune) rune {
		switch {
		case r >= 'a' && r <= 'z', r >= '0' && r <= '9':
			return r
		case r >= 'A' && r <= 'Z':
			return r + ('a' - 'A')
		default:
			return -1
		}
	}, display)

	return map[string]string{
		"go.mod":            "module " + module + "\n\ngo 1.27.3\n",
		"mygo.json":         "{\n  \"name\": " + strconv.Quote(display) + ",\n  \"identifier\": " + strconv.Quote(identifier) + ",\n  \"out\": \"dist\"\n}\n",
		".gitignore":        ".bifrost/\ndist/\n",
		"main.go":           nativeScaffoldMain(display),
		"app/page.go":       nativeScaffoldPage(display),
		"app/about/page.go": nativeScaffoldAbout(display),
		"app/layout.go":     nativeScaffoldLayout(display),
		"app/error.go":      nativeScaffoldError(),
		"app/not-found.go":  nativeScaffoldNotFound(),
	}
}

func nativeScaffoldMain(name string) string {
	return `package main

import (
	"log"

	"github.com/egoist/mygo"
	"github.com/egoist/mygo/ui"
)

// app holds what the screens share: the client of the server, the state.
type app struct{}

func main() {
	instance := &app{}
	mygo.App.WhenReady(func() {
		mygo.NewWindow(mygo.WindowOptions{
			Title:   ` + strconv.Quote(name) + `,
			Width:   900,
			Height:  700,
			Content: ui.View(instance.view),
		})
	})
	if err := mygo.App.Run(); err != nil {
		log.Fatal(err)
	}
}

// view draws the page of the path. appPages is generated by bifrost build
// from the Screen function of each page.go under app/.
func (a *app) view(c *ui.Context) {
	router := ui.NewRouter("/")
	router.View(c, func(r *ui.Route) {
		for _, page := range appPages(a) {
			if r.Match(page.Pattern) {
				page.View(c)
				return
			}
		}
		ui.Text(c, "Not found")
	})
}
`
}

func nativeScaffoldPage(name string) string {
	return `package app

import (
	"net/http"

	"github.com/3-lines-studio/bifrost/mygo/seo"
	"github.com/egoist/mygo/ui"
)

// Props is what Load passes to View and Metadata.
type Props struct {
	Title string
}

// Load runs on the server for every request.
func Load(*http.Request) (any, error) {
	return Props{Title: ` + strconv.Quote(name) + `}, nil
}

// View draws the page: the server renders it to HTML for crawlers, and the
// app draws the same view in the window and the browser.
func View(props Props) func(*ui.Context) {
	return func(c *ui.Context) {
		ui.Column(c).Padding(24).Gap(12).Children(func() {
			ui.Text(c, props.Title).FontSize(32).Bold().Role(ui.RoleHeading).Level(1)
			ui.Text(c, "Edit app/page.go to change this page.")
			seo.Link(c, "About", "/about")
		})
	}
}

// Metadata is what a crawler reads.
func Metadata(props Props) seo.Head {
	return seo.Head{
		Title:       props.Title,
		Description: "One source for the server, the browser and the desktop",
		Canonical:   "https://example.com/",
	}
}

// Screen is the page in the app: appPages gives it to the router.
func Screen() func(*ui.Context) {
	return View(Props{Title: ` + strconv.Quote(name) + `})
}

// Cache is the Cache-Control header of the server-rendered page.
func Cache() string {
	return "public, s-maxage=60"
}
`
}

